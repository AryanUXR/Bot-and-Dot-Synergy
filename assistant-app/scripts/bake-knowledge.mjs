// Copies the skill's knowledge files into the app at build time, so the deployed
// function never reads outside its own folder. Run by `npm run dev` and `npm run build`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..", "..");
const out = path.resolve(here, "..", "src", "generated", "knowledge.ts");

// 1. Check every fact against the source texts, then write the facts table (counsel/facts.md)
//    and the copy the server's reply checker uses (src/generated/facts.ts).
const factsJson = path.join(repo, "counsel", "facts.json");
if (fs.existsSync(factsJson)) {
  execFileSync(process.execPath, [path.join(repo, "counsel", "check_facts.mjs")], { stdio: "inherit" });
  const data = JSON.parse(fs.readFileSync(factsJson, "utf8"));
  const order = data.places;
  const lines = [
    "# Blue Dots facts table",
    "",
    "Generated from `facts.json` by the assistant's bake step. Do not edit by hand. Every figure about Blue Dots the assistant states must come from a row here: say the row's place, use its wording, and cite its id in square brackets, e.g. [F23].",
    "",
  ];
  for (const place of order) {
    const rows = data.facts.filter((f) => f.places[0] === place);
    if (!rows.length) continue;
    lines.push(`## ${place}`, "", "| Id | Figure | Also true for | Source | Topic |", "|---|---|---|---|---|");
    for (const f of rows) {
      const also = f.places.slice(1).join(", ") || "";
      const note = f.note ? ` *Note: ${f.note}*` : "";
      lines.push(`| ${f.id} | ${f.claim}${note} | ${also} | ${f.cite} | ${f.topic} |`);
    }
    lines.push("");
  }
  fs.writeFileSync(path.join(repo, "counsel", "facts.md"), lines.join("\n"));
  const slim = data.facts.map(({ id, places, claim, cite, topic }) => ({ id, places, claim, cite, topic }));
  fs.writeFileSync(path.resolve(here, "..", "src", "generated", "facts.ts"),
    `// Generated by scripts/bake-knowledge.mjs from counsel/facts.json. Do not edit by hand.\nexport type Fact = { id: string; places: string[]; claim: string; cite: string; topic: string };\nexport const FACTS: Fact[] = ${JSON.stringify(slim, null, 1)};\n`);
  console.log(`bake-knowledge: wrote facts.md and facts.ts (${slim.length} facts)`);
}

const FILES = [
  ["Counsel skill: how to answer and run the fit check", "counsel/SKILL.md"],
  ["Knowledge base: what EkStep's Blue Dots documents say", "counsel/knowledge.md"],
  ["Facts table: every figure, its place and its source", "counsel/facts.md"],
  ["The ten non-negotiables", "onboarding/non-negotiables.md"],
  ["How to write personas", "content/persona-writing-guide.md"],
  ["How to write dot data", "content/dot-data-guide.md"],
  ["Voice bot prompt anatomy", "bot/prompt-anatomy.md"],
];

const parts = [];
for (const [title, rel] of FILES) {
  const p = path.join(repo, rel);
  if (!fs.existsSync(p)) {
    if (fs.existsSync(out)) { console.log(`bake-knowledge: ${rel} not found, keeping the committed copy`); process.exit(0); }
    throw new Error(`bake-knowledge: missing ${rel}`);
  }
  parts.push(`<document title="${title}" source="${rel}">\n${fs.readFileSync(p, "utf8").trim()}\n</document>`);
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `// Generated by scripts/bake-knowledge.mjs. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(parts.join("\n\n"))};\n`);
console.log(`bake-knowledge: wrote ${parts.length} documents`);
